package com.onsemi.mib.model;

public class EquipmentGlobalFamily {

	private String id;
	private String sptsGuid;
	private String createdDate;
	private String familyName;
	private String gefnAuthorizationGuid;
	private String modifiedDate;
	private String modifiedBy;
	private String modifiedSiteId;

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getSptsGuid() {
		return sptsGuid;
	}

	public void setSptsGuid(String sptsGuid) {
		this.sptsGuid = sptsGuid;
	}

	public String getCreatedDate() {
		return createdDate;
	}

	public void setCreatedDate(String createdDate) {
		this.createdDate = createdDate;
	}

	public String getFamilyName() {
		return familyName;
	}

	public void setFamilyName(String familyName) {
		this.familyName = familyName;
	}

	public String getGefnAuthorizationGuid() {
		return gefnAuthorizationGuid;
	}

	public void setGefnAuthorizationGuid(String gefnAuthorizationGuid) {
		this.gefnAuthorizationGuid = gefnAuthorizationGuid;
	}

	public String getModifiedDate() {
		return modifiedDate;
	}

	public void setModifiedDate(String modifiedDate) {
		this.modifiedDate = modifiedDate;
	}

	public String getModifiedBy() {
		return modifiedBy;
	}

	public void setModifiedBy(String modifiedBy) {
		this.modifiedBy = modifiedBy;
	}

	public String getModifiedSiteId() {
		return modifiedSiteId;
	}

	public void setModifiedSiteId(String modifiedSiteId) {
		this.modifiedSiteId = modifiedSiteId;
	}

}