package com.onsemi.mib.model;

public class EquipmentTray {

	private String id;
	private String sptsPkid;
	private String equipmentPkid;
	private String rackTotal;
	private String trayPerBasketZoneCapacity;
	private String trayZoneCapacity;
	private String basketZoneCapacity;
	private String trayPerZoneCapacity;
	private String basketPerZoneCapacity;

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getSptsPkid() {
		return sptsPkid;
	}

	public void setSptsPkid(String sptsPkid) {
		this.sptsPkid = sptsPkid;
	}

	public String getEquipmentPkid() {
		return equipmentPkid;
	}

	public void setEquipmentPkid(String equipmentPkid) {
		this.equipmentPkid = equipmentPkid;
	}

	public String getRackTotal() {
		return rackTotal;
	}

	public void setRackTotal(String rackTotal) {
		this.rackTotal = rackTotal;
	}

	public String getTrayPerBasketZoneCapacity() {
		return trayPerBasketZoneCapacity;
	}

	public void setTrayPerBasketZoneCapacity(String trayPerBasketZoneCapacity) {
		this.trayPerBasketZoneCapacity = trayPerBasketZoneCapacity;
	}

	public String getTrayZoneCapacity() {
		return trayZoneCapacity;
	}

	public void setTrayZoneCapacity(String trayZoneCapacity) {
		this.trayZoneCapacity = trayZoneCapacity;
	}

	public String getBasketZoneCapacity() {
		return basketZoneCapacity;
	}

	public void setBasketZoneCapacity(String basketZoneCapacity) {
		this.basketZoneCapacity = basketZoneCapacity;
	}

	public String getTrayPerZoneCapacity() {
		return trayPerZoneCapacity;
	}

	public void setTrayPerZoneCapacity(String trayPerZoneCapacity) {
		this.trayPerZoneCapacity = trayPerZoneCapacity;
	}

	public String getBasketPerZoneCapacity() {
		return basketPerZoneCapacity;
	}

	public void setBasketPerZoneCapacity(String basketPerZoneCapacity) {
		this.basketPerZoneCapacity = basketPerZoneCapacity;
	}

}