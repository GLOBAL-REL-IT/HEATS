package com.onsemi.mib.model;

public class Hardware {

	private String id;
	private String itemId;
	private String hwConfigId;
	private String hardwareName;
	private String alu;
	private String mfgDate;
	private String registeredDate;
	private String rmsEvent;
	private String status;
	private String enableAlu;
	private String movementAlu;
	private String createdDate;
	private String createdBy;
	private String flag;

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getItemId() {
		return itemId;
	}

	public void setItemId(String itemId) {
		this.itemId = itemId;
	}

	public String getHwConfigId() {
		return hwConfigId;
	}

	public void setHwConfigId(String hwConfigId) {
		this.hwConfigId = hwConfigId;
	}

	public String getHardwareName() {
		return hardwareName;
	}

	public void setHardwareName(String hardwareName) {
		this.hardwareName = hardwareName;
	}

	public String getAlu() {
		return alu;
	}

	public void setAlu(String alu) {
		this.alu = alu;
	}

	public String getMfgDate() {
		return mfgDate;
	}

	public void setMfgDate(String mfgDate) {
		this.mfgDate = mfgDate;
	}

	public String getRegisteredDate() {
		return registeredDate;
	}

	public void setRegisteredDate(String registeredDate) {
		this.registeredDate = registeredDate;
	}

	public String getRmsEvent() {
		return rmsEvent;
	}

	public void setRmsEvent(String rmsEvent) {
		this.rmsEvent = rmsEvent;
	}

	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

	public String getEnableAlu() {
		return enableAlu;
	}

	public void setEnableAlu(String enableAlu) {
		this.enableAlu = enableAlu;
	}

	public String getMovementAlu() {
		return movementAlu;
	}

	public void setMovementAlu(String movementAlu) {
		this.movementAlu = movementAlu;
	}

	public String getCreatedDate() {
		return createdDate;
	}

	public void setCreatedDate(String createdDate) {
		this.createdDate = createdDate;
	}

	public String getCreatedBy() {
		return createdBy;
	}

	public void setCreatedBy(String createdBy) {
		this.createdBy = createdBy;
	}

	public String getFlag() {
		return flag;
	}

	public void setFlag(String flag) {
		this.flag = flag;
	}

}